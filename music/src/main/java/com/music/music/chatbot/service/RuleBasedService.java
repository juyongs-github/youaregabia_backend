    public String getResponse(String message) {
        String lowerMsg = message.toLowerCase();
        for (Map.Entry<String[], String> entry : RULES) {
            for (String keyword : entry.getKey()) {
                if (lowerMsg.contains(keyword)) {
                    return entry.getValue().trim();
                }
            }
        }
        return null;
    }
